//! Стенд сравнения распознавателей — то, из чего он собран.
//!
//! Спека — `docs/superpowers/specs/2026-08-28-asr-bench-design.md`,
//! план — `docs/superpowers/plans/2026-08-28-asr-bench.md`.
//!
//! В приложение не входит: это прибор, как `stt-probe` и `diarize-probe`,
//! и с той же дисциплиной — заведомо положительный и заведомо
//! отрицательный случай раньше настоящих данных.
//!
//! Отвечает на вопрос, на который `stt-probe` отвечать отказывается: не
//! «работает ли движок вообще», а «который из них и с какой нарезкой
//! лучше на наших встречах». Разница в том, что здесь есть эталон; без
//! него сравнение расшифровки с расшифровкой — сверка догадки самой с
//! собой.
//!
//! **Библиотека, а не один бинарь**, по простой причине: метрики нужны и
//! отсюда, и из соседних приборов (`stt-probe` уже включает `wer.rs`
//! файлом). Заодно это снимает вечное «функция не используется» у кода,
//! написанного на шаг вперёд.

// Whisper и sherpa-onnx в одном бинаре на Linux не уживаются, и это
// **замерено**, а не предположено:
//
//   сборка gigaam                → WER 0.000, работает
//   сборка whisper               → WER 0.000, работает
//   сборка whisper + gigaam      → whisper работает, gigaam падает
//   сборка whisper + vad         → падает на первом же вызове VAD
//
// Падение — `free(): invalid pointer` внутри пути sherpa. Причина не
// найдена, и две очевидные догадки проверены и **отвергнуты**: общих
// символов ggml нет (у библиотек sherpa их ноль), пересечение
// определённых символов между двумя наборами статических библиотек —
// пусто, рантайм-библиотеки те же самые.
//
// Запрет узкий намеренно: доказательство есть только для Linux. На Маке
// у sherpa другие сборки библиотек, у whisper — Metal вместо CPU, и
// повторяется ли там это, **неизвестно**. Расширять запрет по догадке
// значило бы запретить сочетание, на котором приложение уже собирается.
#[cfg(all(
    target_os = "linux",
    feature = "whisper",
    any(
        feature = "gigaam",
        feature = "parakeet",
        feature = "tone",
        feature = "vad",
        feature = "diarize"
    )
))]
compile_error!(
    "на Linux whisper и sherpa-onnx в одном бинаре не уживаются: сторона sherpa \
     падает с free(): invalid pointer. Собирай стенд либо с --features whisper, \
     либо с движками на sherpa, но не вместе"
);

