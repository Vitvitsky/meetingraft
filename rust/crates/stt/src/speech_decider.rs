//! Кто решает, есть ли речь в кадре.
//!
//! Заведено ради сравнения двух таких решателей на одном материале
//! (`gate-probe`): гейта по энергии, который стоит в живом пути, и
//! Silero VAD, который обещан ADR-005 и до сих пор не построен.
//!
//! **Сравнение имеет смысл, только пока меняется одно.** Всё, что идёт
//! после решения — накопление речи до `MIN_SPEECH_FRAMES`, закрытие
//! реплики по `SILENCE_FRAMES`, темп `InferencePacer`, — общее и
//! неизменное. Иначе разница в запусках модели окажется разницей двух
//! правил сразу, и приписать её решателю будет нельзя.

/// Решение о кадре: есть ли в нём речь.
///
/// Кадр, а не уровень: гейту хватает RMS, а VAD нужны сами отсчёты.
/// Общий вход — единственное, на чём их можно поставить рядом.
pub trait SpeechDecider {
    fn accepts_frame(&mut self, frame: &[i16]) -> bool;

    /// Как решатель называется в отчётах прибора.
    fn name(&self) -> &'static str;

    /// Забыть накопленное: новая запись — новая комната.
    fn reset(&mut self);
}

impl SpeechDecider for crate::NoiseGate {
    fn accepts_frame(&mut self, frame: &[i16]) -> bool {
        self.accepts(crate::frame_rms(frame))
    }

    fn name(&self) -> &'static str {
        "гейт по фону"
    }

    fn reset(&mut self) {
        crate::NoiseGate::reset(self);
    }
}
