//! Что движок-transducer услышал в куске аудио.
//!
//! Общий тип для GigaAM и parakeet, и это не обобщение впрок: оба —
//! transducer через sherpa-onnx, оба отдают текст, слова с временем и
//! границы речи, и различаются только разбором токенов. Тип, названный
//! по одному из движков, второму пришлось бы либо копировать, либо
//! тянуть за собой его фичу.

use crate::local_agreement::HypothesisWord;

/// Что движок услышал в куске аудио.
#[derive(Debug, Clone, Default)]
pub struct TransducerHypothesis {
    /// Текст целиком, как его собрал sherpa-onnx.
    pub text: String,
    /// Слова с временем окончания от начала поданного куска.
    ///
    /// Пусто, если модель не отдала тайм-кодов: поле `timestamps` у
    /// результата — `Option`, и притворяться, что время известно, хуже,
    /// чем сказать, что его нет.
    pub words: Vec<HypothesisWord>,
    /// Границы речи внутри куска: первый и последний символ.
    ///
    /// Отдельно от `words`, потому что у слова здесь известен только
    /// конец, а начало куска — это начало **первого символа первого
    /// слова**. Считать началом конец первого слова значит выкинуть его
    /// из собственного сегмента, а на однословном окне — получить
    /// сегмент нулевой длины.
    pub speech_ms: Option<(u64, u64)>,
}

/// Контекстное смещение: список терминов, которым помогают выжить в
/// поиске.
///
/// **Первый механизм глоссария, влияющий на само распознавание**, а не
/// правящий текст после него. У transducer'а он устроен автоматом
/// Ахо-Корасик поверх лучей поиска.
///
/// Два условия, оба жёсткие и оба молчаливые при нарушении:
///
/// 1. Работает **только** с `modified_beam_search`. На жадном поиске,
///    который стоит по умолчанию, лучей нет вовсе — и смещение не делает
///    ничего. Настройка при этом принимается без слова.
/// 2. Фраза разбивается на единицы модели, и разбиение задаётся
///    `modeling_unit`. Ошибиться в нём — получить термин, которого в
///    словаре нет ни одним куском, то есть снова ничего.
///
/// Отсюда правило: смещение считается работающим не тогда, когда оно
/// настроено, а когда замер показал разницу.
#[derive(Debug, Clone)]
pub struct Biasing {
    /// Файл с терминами: по одному на строку.
    pub hotwords: std::path::PathBuf,
    /// Насколько сильно помогать. Больше — легче протащить термин и
    /// легче притянуть похожее на него постороннее.
    pub score: f32,
}

/// Умолчание силы смещения.
///
/// Значение из документации sherpa; своё оно получит замером, у которого
/// **две** стороны: пойманные термины и притянутые посторонние слова.
/// Смещение, у которого меряют только первую, всегда выглядит успешным.
pub const DEFAULT_HOTWORDS_SCORE: f32 = 1.5;
