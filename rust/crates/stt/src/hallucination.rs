//! Отсев типовых галлюцинаций Whisper (особенно на тишине / шуме).

/// Нормализованный текст — кандидат на отбрасывание.
pub fn is_whisper_hallucination(text: &str) -> bool {
    let normalized = normalize(text);
    if normalized.is_empty() {
        return true;
    }
    // Слишком короткие «обрывки» после нормализации часто мусор.
    if normalized.chars().count() < 2 {
        return true;
    }
    if credits_line(&normalized) {
        return true;
    }
    HALLUCINATION_MARKERS
        .iter()
        .any(|marker| normalized.contains(marker))
}

/// Титры вида «субтитры <глагол> <имя>».
///
/// Проверяется стем плюс глагол, а не готовая фраза целиком. Разница
/// стоила живого дефекта: список полных фраз перечислял «сделал»,
/// «делал», «создал», «создавал», «добавил», «подготовил» — и пропустил
/// «Субтитры подогнал Игорь Негода», вылезший 5–10 раз на одной встрече
/// (2026-08-18). Своим же комментарием список обещал полноту, которой у
/// перечисления не бывает.
///
/// Так одна новая форма закрывается одной строкой и сразу во всех
/// склонениях стема: «субтитры», «субтитров», «субтитрами».
///
/// Порядок обязателен — глагол **после** стема. Иначе «добавили
/// субтитры» из живой речи (а это приложение как раз про субтитры)
/// улетало бы как галлюцинация.
fn credits_line(normalized: &str) -> bool {
    // Вхождений стема бывает несколько, и титры могут висеть на втором:
    // «обсудили субтитры в проекте, субтитры подогнал автор». Смотреть
    // только первое значит судить по речи о том, что сказала модель
    // дальше.
    normalized
        .match_indices(CREDIT_SUBJECT)
        .any(|(start, _)| verb_follows(&normalized[start + CREDIT_SUBJECT.len()..]))
}

/// Идёт ли следом за стемом глагол титров — целым словом и близко.
fn verb_follows(tail: &str) -> bool {
    let mut words = tail.split_whitespace();
    // Первое «слово» — окончание самого стема («ы», «ов», «ами»), если
    // хвост начался вплотную. За глагол оно не считается.
    if !tail.starts_with(char::is_whitespace) {
        words.next();
    }
    let window: Vec<&str> = words.take(CREDIT_WINDOW_WORDS).collect();
    if window.is_empty() {
        return false;
    }
    // Границы слов обязательны. Без них «правил» сидит внутри
    // «правильно», «перевел» — внутри «перевели», а «и перевод» — внутри
    // «или перевод»: речь про субтитры съедалась бы целиком, и это в
    // приложении, которое как раз про субтитры.
    let padded = format!(" {} ", window.join(" "));
    CREDIT_VERBS
        .iter()
        .any(|verb| padded.contains(&format!(" {verb} ")))
}

/// Стем, покрывающий все склонения слова.
const CREDIT_SUBJECT: &str = "субтитр";

/// Насколько далеко за стемом искать глагол, в словах.
///
/// Титры — короткая формула, но со вставкой: «Субтитры **для этого
/// видео** сделал Игорь». Четыре слова покрывают её и не дотягиваются
/// до «субтитры у нас на встрече не работали, зато Игорь сделал
/// дашборд», где глагол восьмой.
const CREDIT_WINDOW_WORDS: usize = 4;

/// Длиннее этого начало титров не бывает: стем и начатое следующее
/// слово.
///
/// Придержанный кусок ждёт следующей порции, склеивается с ней и
/// проверяется заново (`whisper.rs`). Держать по стему целое
/// предложение нельзя: «Субтитры вчера не работали» ушло бы из живых
/// субтитров до самого flush, а на складке могло бы и пропасть совсем.
const CREDIT_PREFIX_WORDS: usize = 2;

/// Глаголы, которыми подписывают титры. Здесь же — обе формы «ё»:
/// нормализация регистр приводит, а «ё» к «е» — нет.
const CREDIT_VERBS: &[&str] = &[
    "сделал",
    "делал",
    "создал",
    "создавал",
    "добавил",
    "подготовил",
    "подогнал",
    "подгонял",
    "перевел",
    "перевёл",
    "правил",
    "редактировал",
    "озвучил",
    "предоставлены",
    "и перевод",
];

/// Текст — **начало** известной галлюцинации, но ещё не она целиком.
///
/// Нужен потому, что LocalAgreement фиксирует текст порциями по мере
/// согласия (ADR-010): «Субтитры сделал DimaTorzok» приходит по кускам,
/// и каждый кусок по отдельности выглядит безобидно. Проверка целой
/// фразы срабатывает слишком поздно — начало уже отдано.
///
/// Выбросить такой кусок нельзя: «субтитры» бывает и настоящим словом.
/// Его придерживают до следующего шага, где станет ясно, чем он был.
pub fn is_hallucination_prefix(text: &str) -> bool {
    let normalized = normalize(text);
    // Порог против ложных задержек: без него «па» задерживалось бы как
    // начало «пара имен», а «ко» — как начало «корректор а». Реальная
    // речь тормозилась бы на пустом месте.
    if normalized.chars().count() < MIN_PREFIX_CHARS {
        return false;
    }
    // Начало титров — сам стем: глагол ещё не приехал, и какой он
    // будет, неизвестно. Держим до следующего шага, где станет ясно,
    // титры это или речь про субтитры.
    if normalized.starts_with(CREDIT_SUBJECT)
        && normalized.split_whitespace().count() <= CREDIT_PREFIX_WORDS
        && !credits_line(&normalized)
    {
        return true;
    }
    HALLUCINATION_MARKERS
        .iter()
        .any(|marker| marker.len() > normalized.len() && marker.starts_with(&normalized))
}

/// Короче этого начало фразы не опознаётся: слишком много совпадений.
const MIN_PREFIX_CHARS: usize = 5;

fn normalize(text: &str) -> String {
    text.chars()
        .map(|c| {
            if c.is_alphanumeric() || c.is_whitespace() {
                c.to_lowercase().next().unwrap_or(c)
            } else {
                ' '
            }
        })
        .collect::<String>()
        .split_whitespace()
        .collect::<Vec<_>>()
        .join(" ")
}

/// Подстроки после `normalize` (нижний регистр, без пунктуации).
const HALLUCINATION_MARKERS: &[&str] = &[
    // Классика RU YouTube / softsub — но только те, где глагола нет
    // вовсе: с глаголом разбирается `credits_line`, и дублировать их
    // здесь значит завести второй список, который разойдётся с первым.
    "авторы субтитров",
    "автор субтитров",
    "редактор субтитров",
    "переводчик субтитров",
    // Самый частый «автор» русских титров в обучающем корпусе. Как
    // слово в речи не встречается, поэтому ловится и без контекста.
    "dimatorzok",
    "дима торжок",
    "димасторжок",
    // Второй такой же «автор», пойманный на живой встрече 2026-08-18.
    // Имя ловится отдельно от фразы: LocalAgreement мог отдать вводную
    // часть раньше, и приехать может только оно.
    "игорь негода",
    "продолжение следует",
    "подписывайтесь на канал",
    "спасибо за просмотр",
    "спасибо за внимание всем",
    "ставьте лайк",
    "пара имен",
    "корректор а",
    "амara org",
    "amara org",
    // EN / mixed
    "thanks for watching",
    "thank you for watching",
    "subscribe to",
    "subtitles by",
    "字幕",
    "www ",
    "http",
];

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn drops_russian_credits_hallucination() {
        assert!(is_whisper_hallucination("Авторы субтитров и пара имен"));
        assert!(is_whisper_hallucination("авторы субтитров А. Иванов"));
    }

    #[test]
    fn keeps_real_meeting_speech() {
        assert!(!is_whisper_hallucination(
            "Давайте обсудим roadmap на следующий спринт"
        ));
        assert!(!is_whisper_hallucination("Welcome to MeetingRaft"));
    }

    /// Формы глагола проверяются правилом, а не перечислением фраз:
    /// перечисление уже подводило (см. `drops_the_credits_line_that_slipped_through`).
    #[test]
    fn drops_verb_variants_of_the_credits_line() {
        for text in [
            "Субтитры сделал DimaTorzok",
            "Субтитры создавал DimaTorzok",
            "Субтитры делал Дима Торжок",
            "Субтитры и перевод: студия",
            "Спасибо за просмотр!",
        ] {
            assert!(is_whisper_hallucination(text), "пропущено: {text}");
        }
    }

    /// Имя «автора» титров ловится и без вводной фразы: LocalAgreement
    /// мог отдать её раньше отдельным куском.
    #[test]
    fn drops_the_credited_name_alone() {
        assert!(is_whisper_hallucination("DimaTorzok"));
        assert!(is_whisper_hallucination("Дима Торжок"));
    }

    /// Дефект с живой встречи 2026-08-18: строка вылезала 5–10 раз.
    ///
    /// Формы «подогнал» в списке не было, а список полных фраз своим же
    /// комментарием обещал полноту.
    #[test]
    fn drops_the_credits_line_that_slipped_through() {
        assert!(is_whisper_hallucination("Субтитры подогнал Игорь Негода"));
        // Без имени — то же самое: правило держится на глаголе, а не на
        // том, кого модель назвала автором в этот раз.
        assert!(is_whisper_hallucination("Субтитры подогнал"));
        assert!(is_whisper_hallucination("Игорь Негода"));
    }

    /// Стем закрывает склонения, а не только именительный падеж.
    #[test]
    fn the_stem_covers_the_declensions() {
        assert!(is_whisper_hallucination(
            "Редактор субтитров подогнал текст"
        ));
        assert!(is_whisper_hallucination("Субтитров создал не я"));
    }

    /// Глагол не из списка титрами не делает.
    ///
    /// «Субтитрами занимался Игорь» — рабочая фраза этой самой команды, и
    /// широкий список глаголов съел бы её. Полнота списка здесь не цель:
    /// цена ошибок не равна, пропущенная строка титров видна глазами, а
    /// съеденная реплика — нет.
    #[test]
    fn a_verb_outside_the_list_is_ordinary_speech() {
        assert!(!is_whisper_hallucination("Субтитрами занимался Игорь"));
    }

    /// Порядок обязателен: глагол после стема.
    ///
    /// Это приложение как раз про субтитры, и говорить о них на встрече
    /// будут. «Добавили субтитры» — речь, а не титры.
    #[test]
    fn speech_about_subtitles_survives() {
        assert!(!is_whisper_hallucination(
            "Мы добавили субтитры в приложение"
        ));
        assert!(!is_whisper_hallucination("Субтитры вчера не работали"));
    }

    /// Глагол далеко за стемом титрами не считается.
    #[test]
    fn a_verb_far_from_the_stem_is_not_a_credits_line() {
        assert!(!is_whisper_hallucination(
            "Субтитры у нас на встрече не работали, зато Игорь сделал дашборд"
        ));
    }

    /// Начало титров держится независимо от того, какой глагол приедет.
    /// Разбор ревью 2026-08-19: правило съедало речь про субтитры.
    ///
    /// Глаголы искались подстрокой, а «правил» сидит внутри
    /// «правильно», «перевел» — внутри «перевели», «и перевод» — внутри
    /// «или перевод». В приложении про субтитры это самые обычные
    /// фразы, и терялись они молча.
    #[test]
    fn speech_that_merely_contains_a_verb_inside_a_word_survives() {
        for text in [
            "Субтитры правильно отображаются",
            "Субтитры поправили в проде",
            "Субтитры или перевод",
            "Субтитры перевели на английский",
        ] {
            assert!(!is_whisper_hallucination(text), "съедено: {text}");
        }
    }

    /// Титры на втором упоминании стема.
    ///
    /// Живой путь проверяет **склеенную** гипотезу (`whisper.rs`): в ней
    /// человек упомянул субтитры, а модель дописала титры в конце.
    #[test]
    fn credits_after_real_speech_are_still_caught() {
        // Между упоминаниями больше слов, чем в окне: иначе проверка
        // проходит и по первому вхождению, и тест перестаёт отличать
        // «смотрим все» от «смотрим первое». Поймано мутацией.
        assert!(is_whisper_hallucination(
            "Мы обсудили субтитры в этом проекте на прошлой неделе, субтитры подогнал автор"
        ));
    }

    /// Формула со вставкой — самая частая в корпусе.
    #[test]
    fn credits_with_words_in_between_are_caught() {
        assert!(is_whisper_hallucination(
            "Субтитры для этого видео сделал Игорь"
        ));
        assert!(is_whisper_hallucination(
            "Субтитры к данному видео подготовил Иван"
        ));
    }

    /// Целое предложение по стему не держится.
    ///
    /// Придержанное склеивается со следующей порцией и проверяется
    /// заново; на складке фраза может уехать в галлюцинации целиком.
    /// До разбора ревью «Субтитры вчера не работали» держалось до
    /// самого flush.
    #[test]
    fn a_whole_sentence_starting_with_the_stem_is_not_held() {
        assert!(!is_hallucination_prefix("Субтитры вчера не работали"));
        assert!(!is_hallucination_prefix("Субтитры у нас не показываются"));
    }

    #[test]
    fn the_stem_alone_is_held_back() {
        assert!(is_hallucination_prefix("Субтитры"));
        assert!(is_hallucination_prefix("субтитры подо"));
    }

    #[test]
    fn holds_back_the_beginning_of_a_known_phrase() {
        assert!(is_hallucination_prefix("Субтитры"));
        assert!(is_hallucination_prefix("субтитры сдел"));
    }

    /// Целая фраза уже не «начало»: её надо выбрасывать, а не держать.
    #[test]
    fn complete_phrase_is_not_a_prefix() {
        assert!(!is_hallucination_prefix("Субтитры сделал DimaTorzok"));
    }

    /// Обычная речь не должна задерживаться ни на шаг.
    #[test]
    fn real_speech_is_not_held_back() {
        assert!(!is_hallucination_prefix("Давайте начнём"));
        assert!(!is_hallucination_prefix("суббота"));
        assert!(!is_hallucination_prefix(""));
    }

    /// Короткие обрывки совпадают с началом слишком многого: «па» — это
    /// «пара имен», «ко» — «корректор». Задерживать их нельзя.
    #[test]
    fn short_fragments_are_not_treated_as_a_beginning() {
        for text in ["па", "ко", "суб", "ht"] {
            assert!(!is_hallucination_prefix(text), "задержано: {text}");
        }
    }
}
