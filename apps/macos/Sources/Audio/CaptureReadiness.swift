import Foundation

/// Что известно про разрешение на микрофон, **без** запроса.
enum MicrophonePermission: Equatable, Sendable {
    /// Ещё не спрашивали: системный запрос появится при первой записи.
    case notAsked
    case granted
    /// Отказано или закрыто политикой. Программа спросить больше не может
    /// — только человек в системных настройках.
    case denied
}

/// Что мешает начать запись прямо сейчас.
///
/// Заведено потому, что до первой записи приложение не говорило о
/// разрешениях **ничего**: узнать, что микрофон запрещён, можно было
/// только нажав «запись» и получив строку ошибки. Для продукта, где
/// худший исход — человек, уверенный, что встреча пишется, это неверный
/// порядок: состояние должно быть видно до нажатия, а не после.
///
/// Когда всё в порядке, состояние `ready` и показывать нечего: плашка
/// «разрешения выданы» — украшение, а не сообщение.
enum CaptureReadiness: Equatable {
    /// Оба канала доступны — показывать нечего.
    case ready
    /// Запрос на микрофон ещё не приходил; он появится при первой записи.
    case microphoneWillBeAsked
    /// Микрофона не будет вовсе: без него записывать нечего.
    case microphoneDenied
    /// Микрофон есть, системного звука не будет — запишется монолог.
    ///
    /// Причину несёт сам статус, а объясняет её `SystemAudioUnavailableBadge`:
    /// он умеет все случаи и уже переведён. Второго набора объяснений
    /// здесь заводить нельзя — они разойдутся.
    case systemAudioUnavailable(SystemAudioStatus)

    /// Что показать при таких разрешениях.
    ///
    /// Порядок важности сверху вниз: без микрофона записи нет вовсе,
    /// поэтому он вытесняет разговор про системный звук. Ничего при этом
    /// не прячется навсегда: после первой записи микрофон переходит в
    /// `granted`, и состояние системного канала становится видимым.
    static func of(
        microphone: MicrophonePermission,
        systemAudio: SystemAudioStatus
    ) -> CaptureReadiness {
        switch microphone {
        case .denied:
            return .microphoneDenied
        case .notAsked:
            return .microphoneWillBeAsked
        case .granted:
            break
        }
        switch systemAudio {
        // `unknown` — разведка ещё не проходила, и сказать нечего.
        // Молчание тут честнее догадки: разрешение может и быть.
        case .granted, .unknown:
            return .ready
        // Отказ, отсутствие устройства вывода, несобравшийся aggregate —
        // разные причины одного исхода: собеседника в записи не будет.
        // Человеку важен исход, и знать о нём он должен **до** встречи, а
        // не по её транскрипту.
        case .denied, .unsupported, .noOutputDevice, .aggregateFailed:
            return .systemAudioUnavailable(systemAudio)
        }
    }
}
